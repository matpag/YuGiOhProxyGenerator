// Build the three native SVG frames from a measured palette and the Nexus texture.
// No resampling, remote requests or modifications to the imported PNG are needed.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const directory=path.join(root,'app/assets/templates/frames');
const palette=JSON.parse(fs.readFileSync(path.join(directory,'egyptian-gods-palette.json'),'utf8'));
const bytes=fs.readFileSync(path.join(root,palette.base.file));
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');
if(sha(bytes)!==palette.base.sha256)throw new Error('The Nexus source changed; recalibrate before rebuilding.');
const number=value=>Number(value.toFixed(8)).toString();
const rectangle=([x,y,width,height])=>`<rect x="${x}" y="${y}" width="${width}" height="${height}"/>`;
const hole=([x,y,width,height])=>`M${x} ${y}h${width}v${height}h-${width}Z`;
const transfer=(name,frame,patch,index)=>{
 const target=frame.target[name],source=palette.base.measurements[name];
 const k=target.contrast,coefficients=[.2126,.7152,.0722].map(value=>value*k);
 const saturation=target.saturation??1;
 const luma=target.rgb.reduce((sum,value,index)=>sum+value*[.2126,.7152,.0722][index],0);
 const rgb=saturation===1?target.rgb:target.rgb.map(value=>luma+(value-luma)*saturation);
 const values=rgb.flatMap(value=>[...coefficients,0,(value-k*source.luma)/255]).concat([0,0,0,1,0]);
 // Extend neighboring opaque body pixels over the gold hairline. SourceAlpha
 // keeps the original outer edge coverage, including partially transparent pixels.
 const id=patch?`edge-${index}`:name;
 const shift=patch?`<feOffset in="SourceGraphic" dx="${patch.offset[0]}" dy="${patch.offset[1]}" result="neighbor"/>`:'';
 const matrix=`<feColorMatrix${patch?' in="neighbor" result="body"':''} type="matrix" values="${values.map(number).join(' ')}"/>`;
 const coverage=patch?'<feComposite in="body" in2="SourceAlpha" operator="in"/>':'';
 return `<filter id="${id}-color" x="0" y="0" width="100%" height="100%" color-interpolation-filters="sRGB">${shift}${matrix}${coverage}</filter>`;
};
const {width,height}=palette.geometry;
const manifest={version:palette.version,geometry:palette.geometry,source:{file:palette.base.file,sha256:palette.base.sha256},palette:'app/assets/templates/frames/egyptian-gods-palette.json',method:palette.method,assets:[]};
for(const [code,frame] of Object.entries(palette.frames)){
 const masks=palette.masks,patches=palette.outer_edge.patches;
 const excluded=[...Object.values(masks).flat(),...patches.map(patch=>patch.rect)].map(hole).join('');
 const definitions=`<image id="texture" width="${width}" height="${height}" href="data:image/png;base64,${bytes.toString('base64')}"/>
<clipPath id="neutral"><path clip-rule="evenodd" d="M0 0h${width}v${height}h-${width}Z${excluded}"/></clipPath>
${Object.entries(masks).map(([name,regions])=>`<clipPath id="${name}">${regions.map(rectangle).join('')}</clipPath>\n${transfer(name,frame)}`).join('\n')}
${patches.map((patch,index)=>`<clipPath id="edge-${index}">${rectangle(patch.rect)}</clipPath>\n${transfer('body',frame,patch,index)}`).join('\n')}`;
 const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<!-- ${frame.name} frame. Generated by scripts/build-egyptian-frames.cjs; color sources are recorded in palette.json. -->
<defs>${definitions}</defs>
<use href="#texture" clip-path="url(#neutral)"/>
${Object.keys(masks).map(name=>`<g clip-path="url(#${name})"><use href="#texture" filter="url(#${name}-color)"/></g>`).join('\n')}
${patches.map((patch,index)=>`<g clip-path="url(#edge-${index})"><use href="#texture" filter="url(#edge-${index}-color)"/></g>`).join('\n')}
</svg>\n`;
 const file=`app/assets/templates/frames/${code}.svg`;
 fs.writeFileSync(path.join(root,file),svg);
 manifest.assets.push({code,name:frame.name,file,sha256:sha(svg)});
 console.log(`${frame.name}: ${width} x ${height}, original alpha and Nexus geometry, ${Buffer.byteLength(svg)} bytes`);
}
(async()=>{
 const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const page=await browser.newPage();
  for(const asset of manifest.assets){
   const svg=fs.readFileSync(path.join(root,asset.file));
   const png=await page.evaluate(async source=>{
    const image=new Image();image.src=source;await image.decode();
    const canvas=document.createElement('canvas');canvas.width=image.naturalWidth;canvas.height=image.naturalHeight;
    canvas.getContext('2d').drawImage(image,0,0);
    return canvas.toDataURL('image/png').split(',')[1];
   },'data:image/svg+xml;base64,'+svg.toString('base64'));
   asset.sourceFile=asset.file;asset.sourceSha256=asset.sha256;
   asset.file=asset.file.replace('.svg','.png');const bytes=Buffer.from(png,'base64');
   fs.writeFileSync(path.join(root,asset.file),bytes);asset.sha256=sha(bytes);
   console.log(asset.name+': native PNG baked, '+bytes.length+' bytes');
  }
  fs.writeFileSync(path.join(directory,'egyptian-gods-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
